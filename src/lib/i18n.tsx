const dicts: Record<Locale, Dict> = { en, zh };

type Ctx = { locale: Locale; setLocale: (l: Locale) => void; t: (k: string, vars?: Record<string, string | number>) => string };
const I18nCtx = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    const saved = (typeof window !== "undefined" && localStorage.getItem("aixin.locale")) as Locale | null;
    if (saved === "en" || saved === "zh") setLocaleState(saved);
  }, []);

  const setLocale = (l: Locale) => {
    setLocaleState(l);
    if (typeof window !== "undefined") localStorage.setItem("aixin.locale", l);
  };

  const t = (k: string, vars?: Record<string, string | number>) => {
    let text = dicts[locale][k] ?? k;
    if (vars) {
      Object.entries(vars).forEach(([key, value]) => {
        text = text.replace(new RegExp(`\\{${key}\\}`, "g"), String(value));
      });
    }
    return text;
  };
  return <I18nCtx.Provider value={{ locale, setLocale, t }}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
